import { CircuitSymbol, SocraticStep } from '../types/circuit.types.ts';

/**
 * Payload sent by the client to analyze an uploaded or pasted circuit diagram image.
 */
export interface CircuitAnalysisRequest {
  /**
   * Base64-encoded image string or Data URL (e.g. data:image/png;base64,...).
   */
  readonly imageBase64: string;

  /**
   * IANA media type of the provided image (e.g. 'image/png', 'image/jpeg', 'image/webp').
   */
  readonly mimeType?: string;

  /**
   * Optional didactic focus or instructor guidelines (e.g., focus on transient analysis).
   */
  readonly pedagogicalFocus?: string;
}

/**
 * Structured synthesized circuit outcome generated by multimodal AI analysis.
 */
export interface CircuitAnalysisResult {
  readonly title: string;
  readonly description: string;
  readonly category: string;
  readonly svgViewBox: string;
  readonly svgContent: string;
  readonly symbols: readonly CircuitSymbol[];
  readonly socraticSteps: readonly SocraticStep[];
}

/**
 * Domain service contract for multimodal schematic analysis.
 */
export interface ICircuitAnalyzerService {
  /**
   * Analyzes a schematic image and synthesizes an educational circuit with SVG and Socratic steps.
   * @param request The analysis payload containing the image.
   * @returns Synthesized circuit data conforming to DeSchema specifications.
   */
  analyzeSchematicImage(request: CircuitAnalysisRequest): Promise<CircuitAnalysisResult>;
}
